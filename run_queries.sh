#!/bin/bash
# ==============================================================================
# run_queries.sh - runs the three requests of 2.3 and writes queries.md
# ==============================================================================
# Each request is run with curl inside the Elasticsearch container and saved
# with its real output in queries.md (the file is rewritten at each run).
# ==============================================================================
set -euo pipefail
cd "$(dirname "$0")"
docker compose ps --status running --services 2>/dev/null | grep -qx elasticsearch \
  || { echo "The stack is not running. Start it first:  ./start.sh" >&2; exit 1; }

OUT=queries.md
PORT=$(grep '^ES_PORT_EXPOSE=' .env | cut -d= -f2-)

# query TITLE PATH BODY : runs "GET PATH" with BODY, appends request + output to queries.md
query() {
  local title=$1 path=$2 body=$3 result
  result=$(printf '%s' "$body" | docker compose exec -T elasticsearch bash -c \
    "curl -s -u \"elastic:\$ELASTIC_PASSWORD\" -H 'Content-Type: application/json' -X GET 'http://localhost:9200/$path' -d @-")
  {
    echo "## $title"
    echo
    echo "Request (Kibana Dev Tools syntax):"
    echo
    echo '```'
    echo "GET $path"
    echo "$body"
    echo '```'
    echo
    echo "Same request with curl:"
    echo
    echo '```bash'
    echo "curl -s -u elastic:<password> -H 'Content-Type: application/json' \\"
    echo "  -X GET 'http://localhost:$PORT/$path' -d '$(printf '%s' "$body" | tr -d '\n' | tr -s ' ')'"
    echo '```'
    echo
    echo "Output:"
    echo
    echo '```json'
    echo "$result"
    echo '```'
    echo
  } >> "$OUT"
  echo "--- $title"; echo "$result"
}

{
  echo "# queries.md - requests on the index bookride-logs"
  echo
  echo "Generated by \`./run_queries.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ). \`<password>\` = password of the user elastic (in .env, never pushed)."
  echo
} > "$OUT"

query "(a) Number of documents with level ERROR" \
  "bookride-logs/_count?pretty" \
'{
  "query": { "term": { "level.keyword": "ERROR" } }
}'

query "(b) Number of documents per service (aggregation)" \
  "bookride-logs/_search?size=0&filter_path=aggregations&pretty" \
'{
  "aggs": { "per_service": { "terms": { "field": "service.keyword" } } }
}'

query "(c) Full-text search for the word \"declined\" in the field message" \
  "bookride-logs/_search?filter_path=hits.total,hits.hits._source&pretty" \
'{
  "query": { "match": { "message": "declined" } }
}'

echo; echo "Saved in $OUT"
